/**
 * Build Validation Report section
 */
function buildValidationReportSection(
  scores: { completeness: number; consistency: number; security: number; implementability: number; overall: number },
  qaIterations: number
): string {
  return `## 8. Validation Report

| Metric | Score |
|--------|-------|
| Completeness | ${scores.completeness}/100 |
| Consistency | ${scores.consistency}/100 |
| Security | ${scores.security}/100 |
| Implementability | ${scores.implementability}/100 |
| **Overall** | **${scores.overall}/100** |

- **QA Iterations:** ${qaIterations}
- **Approval Status:** ${scores.overall >= 70 ? '✅ Approved' : '⚠️ Needs Review'}
`;
}

// ============ Helper Functions ============

function extractValidationScores(validationXml: string): {
  completeness: number;
  consistency: number;
  security: number;
  implementability: number;
  overall: number;
} {
  const defaultScores = { completeness: 0, consistency: 0, security: 0, implementability: 0, overall: 0 };

  if (!validationXml) return defaultScores;

  const completenessMatch = validationXml.match(/<completeness\s+score="(\d+)"/);
  const consistencyMatch = validationXml.match(/<consistency\s+score="(\d+)"/);
  const securityMatch = validationXml.match(/<security\s+score="(\d+)"/);
  const implementabilityMatch = validationXml.match(/<implementability\s+score="(\d+)"/);
  const overallMatch = validationXml.match(/<overall\s+score="(\d+)"/);

  return {
    completeness: completenessMatch ? parseInt(completenessMatch[1], 10) : 0,
    consistency: consistencyMatch ? parseInt(consistencyMatch[1], 10) : 0,
    security: securityMatch ? parseInt(securityMatch[1], 10) : 0,
    implementability: implementabilityMatch ? parseInt(implementabilityMatch[1], 10) : 0,
    overall: overallMatch ? parseInt(overallMatch[1], 10) : 0,
  };
}

function extractEntitySummary(xml: string): string {
  const entities = xml.match(/<entity\s+name="([^"]+)"/g) || [];
  if (entities.length === 0) return 'No entities defined.';

  return entities
    .map((e) => {
      const name = e.match(/name="([^"]+)"/)?.[1] || 'Unknown';
      return `- **${name}**`;
    })
    .join('\n');
}

function extractRelationshipSummary(xml: string): string {
  const relations = xml.match(/<relation[^>]+\/>/g) || [];
  if (relations.length === 0) return 'No relationships defined.';

  return relations
    .map((r) => {
      const from = r.match(/from="([^"]+)"/)?.[1] || '';
      const to = r.match(/to="([^"]+)"/)?.[1] || '';
      const type = r.match(/type="([^"]+)"/)?.[1] || '';
      return `- ${from} → ${to} (${type})`;
    })
    .join('\n');
}

function extractEndpointSummary(xml: string): string {
  const resources = xml.match(/<resource\s+name="([^"]+)"/g) || [];
  if (resources.length === 0) return 'No endpoints defined.';

  const endpoints = xml.match(/<endpoint[^>]+method="([^"]+)"[^>]+path="([^"]+)"/g) || [];

  return `| Method | Path |
|--------|------|
${endpoints
    .slice(0, 15)
    .map((e) => {
      const method = e.match(/method="([^"]+)"/)?.[1] || '';
      const path = e.match(/path="([^"]+)"/)?.[1] || '';
      return `| ${method} | ${path} |`;
    })
    .join('\n')}${endpoints.length > 15 ? `\n\n*...and ${endpoints.length - 15} more endpoints*` : ''}`;
}

function extractAuthSummary(xml: string): string {
  const strategy = xml.match(/<strategy>([^<]+)<\/strategy>/)?.[1] || 'JWT';
  const accessExpiry = xml.match(/<accessTokenExpiry>([^<]+)<\/accessTokenExpiry>/)?.[1] || '15m';
  const refreshExpiry = xml.match(/<refreshTokenExpiry>([^<]+)<\/refreshTokenExpiry>/)?.[1] || '7d';

  return `- **Strategy:** ${strategy}
- **Access Token Expiry:** ${accessExpiry}
- **Refresh Token Expiry:** ${refreshExpiry}`;
}

function extractOwaspSummary(xml: string): string {
  const risks = xml.match(/<risk\s+name="([^"]+)"/g) || [];
  if (risks.length === 0) return 'OWASP coverage not specified.';

  return risks
    .map((r) => {
      const name = r.match(/name="([^"]+)"/)?.[1] || '';
      return `- ✅ ${name}`;
    })
    .join('\n');
}

function extractDataProtectionSummary(xml: string): string {
  const atRest = xml.match(/atRest="([^"]+)"/)?.[1] || 'true';
  const inTransit = xml.match(/inTransit="([^"]+)"/)?.[1] || 'true';

  return `- **Encryption at Rest:** ${atRest === 'true' ? 'Yes' : 'No'}
- **Encryption in Transit:** ${inTransit === 'true' ? 'Yes (TLS)' : 'No'}`;
}

function extractTestSuitesSummary(xml: string): string {
  const suites = xml.match(/<suite\s+name="([^"]+)"/g) || [];
  const resourceSuites = xml.match(/<suite\s+resource="([^"]+)"/g) || [];

  const allSuites = [
    ...suites.map((s) => s.match(/name="([^"]+)"/)?.[1] || ''),
    ...resourceSuites.map((s) => `${s.match(/resource="([^"]+)"/)?.[1] || ''} API Tests`),
  ].filter(Boolean);

  if (allSuites.length === 0) return 'No test suites defined.';

  return allSuites.map((s) => `- ${s}`).join('\n');
}

function extractServicesSummary(xml: string): string {
  const services = xml.match(/<service\s+name="([^"]+)"/g) || [];
  if (services.length === 0) return 'No services defined.';

  return services
    .map((s) => {
      const name = s.match(/name="([^"]+)"/)?.[1] || '';
      return `- **${name}**`;
    })
    .join('\n');
}

function extractHostingSummary(xml: string): string {
  const recommendations = xml.match(/<recommendation\s+provider="([^"]+)"[^>]*>/g) || [];
  if (recommendations.length === 0) return 'No hosting recommendations.';

  return recommendations
    .map((r) => {
      const provider = r.match(/provider="([^"]+)"/)?.[1] || '';
      return `- **${provider}**`;
    })
    .join('\n');
}

export default synthesizePRD;
