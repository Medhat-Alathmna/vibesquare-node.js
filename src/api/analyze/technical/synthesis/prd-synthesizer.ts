/**
 * PRD Synthesizer
 *
 * Combines all agent outputs into a final PRD Markdown document.
 * This is the final step that produces the downloadable PRD file.
 */

import {
  TechnicalPipelineResult,
  VisualPipelineResult,
  DetailLevel,
} from '../core/technical-agent.types';

/**
 * Synthesize final PRD markdown from all agent outputs
 */
export function synthesizePRD(
  technicalResult: TechnicalPipelineResult,
  visualResult: VisualPipelineResult,
  detailLevel: DetailLevel
): string {
  const now = new Date().toISOString();
  const sourceUrl = visualResult.metadata.sourceUrl || 'Unknown';

  // Extract validation scores
  const validationScores = extractValidationScores(technicalResult.validationResult);
  const qaIterations = technicalResult.metadata.qaIterations;

  // Build PRD sections
  const sections: string[] = [];

  // Header
  sections.push(`# Product Requirements Document (PRD)

**Source URL:** ${sourceUrl}
**Generated:** ${now}
**Pipeline:** Visual + Technical
**Detail Level:** ${detailLevel.charAt(0).toUpperCase() + detailLevel.slice(1)}

---
`);

  // 1. Visual Identity
  sections.push(buildVisualIdentitySection(visualResult));

  // 2. Database Schema
  sections.push(buildDatabaseSection(technicalResult.databaseSchema));

  // 3. API Documentation
  sections.push(buildAPISection(technicalResult.backendArchitecture));

  // 4. Security Recommendations
  sections.push(buildSecuritySection(technicalResult.securityRecommendations));

  // 5. Testing Strategy
  sections.push(buildTestingSection(technicalResult.testingStrategy));

  // 6. DevOps Configuration
  sections.push(buildDevOpsSection(technicalResult.devopsConfig));

  // 7. Tech Stack Summary
  sections.push(buildTechStackSection());

  // 8. Validation Report
  sections.push(buildValidationReportSection(validationScores, qaIterations));

  // Footer
  sections.push(`
---

*Generated by VibeSquare V2.5 Technical Architecture Pipeline*
*Total Processing Time: ${technicalResult.metadata.processingTimeMs}ms*
*Agents Used: ${technicalResult.metadata.agentsUsed.join(', ')}*
`);

  return sections.join('\n');
}

/**
 * Build Visual Identity section
 */
function buildVisualIdentitySection(visual: VisualPipelineResult): string {
  const colors = visual.designSystem?.colors || {};
  const fonts = visual.designSystem?.fonts || {};
  const tone = visual.designSystem?.visualTone || 'modern';

  return `## 1. Visual Identity

### 1.1 Color Palette
| Role | Color |
|------|-------|
| Primary | ${colors.primary || '#2563EB'} |
| Secondary | ${colors.secondary || '#64748B'} |
| Accent | ${colors.accent || '#DC2626'} |
| Background | ${colors.background || '#FFFFFF'} |
| Text | ${colors.text || '#1F2937'} |

### 1.2 Typography
- **Headings:** ${fonts.heading || 'Inter'}
- **Body:** ${fonts.body || 'System UI'}

### 1.3 Visual Tone
${tone}

### 1.4 Layout Summary
${visual.layoutAnalysis?.layoutPattern || 'Standard responsive layout'}

### 1.5 Components Detected
${visual.componentIdentification?.components?.map((c) => `- ${c.type}: ${c.count} instance(s)`).join('\n') || '- Standard UI components'}

---
`;
}

/**
 * Build Database Schema section
 */
function buildDatabaseSection(databaseXml: string): string {
  if (!databaseXml) {
    return `## 2. Database Schema

> Database schema not generated.

---
`;
  }

  return `## 2. Database Schema

### 2.1 Schema Definition (XML)

\`\`\`xml
${databaseXml}
\`\`\`

### 2.2 Entity Summary

${extractEntitySummary(databaseXml)}

### 2.3 Relationships

${extractRelationshipSummary(databaseXml)}

---
`;
}

